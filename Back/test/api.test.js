const test=require('node:test');
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const bcrypt=require('bcrypt');
process.env.DB_HOST='localhost';process.env.DB_NAME='dummy';process.env.DB_USER='dummy';process.env.DB_PASSWORD='dummy';
process.env.DB_SSL='false';process.env.SESSION_SECRET=crypto.randomBytes(48).toString('hex');
const Usuario=require('../models/Usuario');
const app=require('../server');
test('API protege sessão e separa perfis sem precisar conectar ao Neon',async(t)=>{
  const server=app.listen(0);
  t.after(()=>new Promise(resolve=>server.close(resolve)));
  const base=`http://127.0.0.1:${server.address().port}`;
  const user={id_usuario:7,nome:'Conta de teste',email:'teste@exemplo.com',senha:await bcrypt.hash('SenhaSegura!123',4),tipo_usuario:'CLIENTE',telefone:null};
  const originalFindOne=Usuario.findOne,originalFindByPk=Usuario.findByPk;
  Usuario.findOne=async()=>user;
  Usuario.findByPk=async()=>user;
  t.after(()=>{Usuario.findOne=originalFindOne;Usuario.findByPk=originalFindByPk;});
  let resp=await fetch(`${base}/api/auth/me`);
  assert.equal(resp.status,401);
  resp=await fetch(`${base}/api/auth/login`,{method:'POST',headers:{'Content-Type':'application/json','Origin':'http://localhost:5173'},body:JSON.stringify({email:'teste@exemplo.com',senha:'SenhaSegura!123'})});
  assert.equal(resp.status,200);
  const cookie=resp.headers.get('set-cookie').split(';')[0];
  assert.ok(resp.headers.get('set-cookie').includes('HttpOnly'));
  resp=await fetch(`${base}/api/auth/me`,{headers:{Cookie:cookie}});
  assert.equal(resp.status,200);
  const body=await resp.json();
  assert.equal(body.usuario.nome,'Conta de teste');
  assert.equal(body.usuario.senha,undefined);
  resp=await fetch(`${base}/api/viagens/minhas`,{headers:{Cookie:cookie}});
  assert.equal(resp.status,403);
  resp=await fetch(`${base}/api/usuarios/123`,{headers:{Cookie:cookie}});
  assert.equal(resp.status,404);
  resp=await fetch(`${base}/api/auth/logout`,{method:'POST',headers:{Cookie:cookie,Origin:'https://evil.example'}});
  assert.equal(resp.status,403);
});
