-- Preserva integralmente a tabela usuarios e seus registros.
BEGIN;
CREATE TABLE IF NOT EXISTS public.viagens (
  id_viagem BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_transportador INTEGER NOT NULL REFERENCES public.usuarios(id_usuario),
  origem VARCHAR(120) NOT NULL,
  destino VARCHAR(120) NOT NULL,
  data_saida DATE NOT NULL,
  veiculo VARCHAR(80) NOT NULL,
  capacidade_m3 NUMERIC(10,2) NOT NULL CHECK (capacidade_m3 > 0),
  status VARCHAR(20) NOT NULL DEFAULT 'AGENDADA' CHECK (status IN ('AGENDADA','EM_ANDAMENTO','CONCLUIDA','CANCELADA')),
  criada_em TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT ck_viagens_rota CHECK (lower(btrim(origem)) <> lower(btrim(destino)))
);
CREATE INDEX IF NOT EXISTS idx_viagens_transportador ON public.viagens(id_transportador);
CREATE INDEX IF NOT EXISTS idx_viagens_status_data ON public.viagens(status, data_saida);
CREATE TABLE IF NOT EXISTS public.cargas (
  id_carga BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente INTEGER NOT NULL REFERENCES public.usuarios(id_usuario),
  origem VARCHAR(120) NOT NULL,
  destino VARCHAR(120) NOT NULL,
  descricao VARCHAR(300) NOT NULL,
  volume_m3 NUMERIC(10,2) NOT NULL CHECK (volume_m3 > 0),
  status VARCHAR(20) NOT NULL DEFAULT 'ABERTA' CHECK (status IN ('ABERTA','NEGOCIACAO','EM_TRANSPORTE','ENTREGUE','CANCELADA')),
  criada_em TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT ck_cargas_rota CHECK (lower(btrim(origem)) <> lower(btrim(destino)))
);
CREATE INDEX IF NOT EXISTS idx_cargas_cliente ON public.cargas(id_cliente);
CREATE INDEX IF NOT EXISTS idx_cargas_status ON public.cargas(status);
CREATE TABLE IF NOT EXISTS public.tokens_recuperacao (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL REFERENCES public.usuarios(id_usuario) ON DELETE CASCADE,
  token_hash VARCHAR(64) NOT NULL UNIQUE,
  expira_em TIMESTAMPTZ NOT NULL,
  usado_em TIMESTAMPTZ,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_tokens_recuperacao_usuario ON public.tokens_recuperacao(usuario_id);
COMMIT;
