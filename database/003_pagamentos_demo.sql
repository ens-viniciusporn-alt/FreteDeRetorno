-- Frete de Retorno | FASE DE TESTES: NENHUMA TRANSAÇÃO REAL.
-- Execute após 001_funcionalidades.sql em banco de DESENVOLVIMENTO/TESTES.
-- Os registros desta migração representam apenas simulações de fluxo financeiro.
BEGIN;
CREATE TABLE IF NOT EXISTS public.contratos_frete_demo (
  id_contrato BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_carga BIGINT NOT NULL REFERENCES public.cargas(id_carga),
  id_viagem BIGINT NOT NULL REFERENCES public.viagens(id_viagem),
  id_cliente INTEGER NOT NULL REFERENCES public.usuarios(id_usuario),
  id_transportador INTEGER NOT NULL REFERENCES public.usuarios(id_usuario),
  valor_centavos BIGINT NOT NULL CHECK(valor_centavos BETWEEN 100 AND 10000000000),
  status VARCHAR(24) NOT NULL DEFAULT 'PROPOSTO'
    CHECK(status IN ('PROPOSTO','ACEITO','GARANTIDO_SIMULADO','ENTREGA_INFORMADA','LIBERADO_SIMULADO','EM_DISPUTA','CANCELADO')),
  descricao_acordo VARCHAR(500) NOT NULL DEFAULT '',
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT contrato_partes_distintas CHECK(id_cliente <> id_transportador)
);
-- Apenas um contrato ainda não cancelado por carga; evita promessas de duplicidade.
CREATE UNIQUE INDEX IF NOT EXISTS ux_contratos_demo_carga_ativa
  ON public.contratos_frete_demo(id_carga) WHERE status <> 'CANCELADO';
CREATE INDEX IF NOT EXISTS ix_contratos_demo_cliente ON public.contratos_frete_demo(id_cliente,criado_em DESC);
CREATE INDEX IF NOT EXISTS ix_contratos_demo_transportador ON public.contratos_frete_demo(id_transportador,criado_em DESC);
CREATE TABLE IF NOT EXISTS public.eventos_contrato_demo (
  id_evento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_contrato BIGINT NOT NULL REFERENCES public.contratos_frete_demo(id_contrato),
  id_usuario INTEGER NOT NULL REFERENCES public.usuarios(id_usuario),
  acao VARCHAR(40) NOT NULL,
  estado_anterior VARCHAR(24),
  estado_novo VARCHAR(24) NOT NULL,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_eventos_contrato_demo ON public.eventos_contrato_demo(id_contrato,id_evento);
COMMIT;
