-- Frete de Retorno - MENSAGENS E NEGOCIACAO DE DEMONSTRACAO
-- Somente branch de testes. Requer 001_funcionalidades.sql e 003_pagamentos_demo.sql.
-- Nao coleta documentos pessoais ou chaves Pix. Nenhum dinheiro e movimentado.
BEGIN;
CREATE TABLE IF NOT EXISTS public.conversas_frete_demo (
  id_conversa BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_carga BIGINT NOT NULL REFERENCES public.cargas(id_carga),
  id_cliente INTEGER NOT NULL REFERENCES public.usuarios(id_usuario),
  id_transportador INTEGER NOT NULL REFERENCES public.usuarios(id_usuario),
  criada_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT conversa_partes_distintas CHECK (id_cliente <> id_transportador),
  CONSTRAINT conversa_unica_por_carga_transportador UNIQUE (id_carga,id_transportador)
);
CREATE INDEX IF NOT EXISTS ix_conversa_cliente ON public.conversas_frete_demo (id_cliente,id_conversa DESC);
CREATE INDEX IF NOT EXISTS ix_conversa_transportador ON public.conversas_frete_demo (id_transportador,id_conversa DESC);
CREATE TABLE IF NOT EXISTS public.mensagens_frete_demo (
  id_mensagem BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_conversa BIGINT NOT NULL REFERENCES public.conversas_frete_demo(id_conversa),
  id_autor INTEGER NOT NULL REFERENCES public.usuarios(id_usuario),
  texto VARCHAR(1000) NOT NULL CHECK(length(btrim(texto))>0),
  criada_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_mensagens_conversa ON public.mensagens_frete_demo (id_conversa,id_mensagem);
COMMIT;
