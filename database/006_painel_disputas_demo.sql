-- Frete de Retorno - somente branch teste-pagamentos. NENHUM VALOR REAL.
-- Cria registro de disputas, manifestacoes e auditoria administrativa.
BEGIN;
CREATE TABLE IF NOT EXISTS public.disputas_frete_demo (
  id_disputa BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_contrato BIGINT NOT NULL UNIQUE REFERENCES public.contratos_frete_demo(id_contrato),
  situacao VARCHAR(24) NOT NULL DEFAULT 'ABERTA' CHECK (situacao IN ('ABERTA','MAIS_INFORMACOES','RESOLVIDA')),
  solicitacao_admin VARCHAR(1000),
  decisao VARCHAR(30),
  justificativa_decisao VARCHAR(1500),
  resolvida_por INTEGER REFERENCES public.usuarios(id_usuario),
  aberta_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  resolvida_em TIMESTAMPTZ,
  atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS public.manifestacoes_disputa_demo (
  id_manifestacao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_disputa BIGINT NOT NULL REFERENCES public.disputas_frete_demo(id_disputa),
  id_autor INTEGER NOT NULL REFERENCES public.usuarios(id_usuario),
  texto VARCHAR(2000) NOT NULL CHECK (length(trim(texto))>=10),
  criada_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_manifestacoes_disputa ON public.manifestacoes_disputa_demo(id_disputa,id_manifestacao);
CREATE TABLE IF NOT EXISTS public.acoes_admin_disputa_demo (
  id_acao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_disputa BIGINT NOT NULL REFERENCES public.disputas_frete_demo(id_disputa),
  id_admin INTEGER NOT NULL REFERENCES public.usuarios(id_usuario),
  acao VARCHAR(30) NOT NULL CHECK (acao IN ('SOLICITAR_INFORMACOES','LIBERAR_SIMULADO','REEMBOLSAR_SIMULADO')),
  justificativa VARCHAR(1500) NOT NULL,
  criada_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_acoes_admin_disputa ON public.acoes_admin_disputa_demo(id_disputa,id_acao);
-- Status adicional para indicar reembolso fictício após mediação.
-- Preserva todos os registros e estados anteriores; troca apenas a validação de status.
DO $$
DECLARE item record;
BEGIN
  FOR item IN
    SELECT conname FROM pg_constraint
    WHERE conrelid='public.contratos_frete_demo'::regclass
      AND contype='c' AND pg_get_constraintdef(oid) LIKE '%status%'
  LOOP
    EXECUTE format('ALTER TABLE public.contratos_frete_demo DROP CONSTRAINT %I',item.conname);
  END LOOP;
END $$;
ALTER TABLE public.contratos_frete_demo ADD CONSTRAINT contratos_frete_demo_status_check
  CHECK (status IN ('PROPOSTO','ACEITO','GARANTIDO_SIMULADO','ENTREGA_INFORMADA','LIBERADO_SIMULADO','EM_DISPUTA','CANCELADO','REEMBOLSADO_SIMULADO'));
COMMIT;
